// tools/swr-journal-log.mjs — append SWR activity to the daily Obsidian
// journal. Subcommands:
//
//   init                              re-emit MOCs and any other init-time files
//   commit <sha> [path]               log a single commit (called by the
//                                     post-commit hook with $1 and $2)
//   event <type> --summary "..."     log a structured event
//   session [summary file]            log a session-end summary block
//   readme                            re-emit the daily journal (no-op idempotent)
//
// Idempotent. The same commit logged twice produces one entry; the
// same event twice appends twice (events are deduplicated on the
// `(type, message)` key inside the day's section).
//
// Path:
//   SWR_VAULT=/path/to/vault node tools/swr-journal-log.mjs <subcommand>
// Default: env SWR_VAULT or the path computed by tools/swr-vault-init.mjs.

import { existsSync, readFileSync, writeFileSync, appendFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const HERE = dirname(fileURLToPath(import.meta.url));
const SWR = join(HERE, '..');

function pickVault() {
  if (process.env.SWR_VAULT) return process.env.SWR_VAULT;
  try {
    return join(SWR, '.obsidian-swr');
  } catch (_) {
    return '/Users/kaidejuricmassbook/Documents/SWR-Vault';
  }
}
const VAULT = pickVault();
const JOURNAL = join(VAULT, 'Journal');
const MOCS = join(VAULT, 'MOCs');

function today() {
  return new Date().toISOString().slice(0, 10);
}
function journalFile() {
  return join(JOURNAL, today() + '.md');
}
function ensureDir(p) {
  if (!existsSync(p)) mkdirSync(p, { recursive: true });
}

function readSafe(p) {
  try { return readFileSync(p, 'utf8'); } catch (_) { return ''; }
}

function shortHash(s) { return (s || '').slice(0, 8); }
function fmtDate(iso) {
  return iso ? iso.slice(0, 10) : today();
}

function getGitContext() {
  try {
    return {
      branch: execSync('git rev-parse --abbrev-ref HEAD', { cwd: SWR, stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim(),
      head:   execSync('git rev-parse HEAD',         { cwd: SWR, stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim(),
      author: execSync('git log -1 --format=%an',     { cwd: SWR, stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim(),
    };
  } catch (_) { return { branch: '?', head: '?', author: '?' }; }
}

function readShow(sha) {
  try {
    return execSync('git show --no-patch --format=%s ' + sha, { cwd: SWR, stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim();
  } catch (_) { return ''; }
}

function readChangedFiles(sha) {
  try {
    return execSync('git show --name-only --format="" ' + sha, { cwd: SWR, stdio: ['pipe', 'pipe', 'pipe'] })
      .toString().trim().split('\n').filter(Boolean);
  } catch (_) { return []; }
}

function readRunTests() {
  // Best-effort: see if there's a recently-passed test artifact. We
  // don't actually re-run npm test here (would be slow), we just check
  // for evidence from the last run.
  try {
    return execSync('node scripts/run-steps.mjs check --list 2>&1', { cwd: SWR, stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim();
  } catch (_) { return ''; }
}

function shortId() {
  return createHash('sha1')
    .update(`${process.pid}|${Date.now()}|${Math.random()}`)
    .digest('hex')
    .slice(0, 8);
}

// ---- Daily header (idempotent) -------------------------------------

function ensureDailyHeader() {
  ensureDir(JOURNAL);
  const fp = journalFile();
  if (existsSync(fp)) return;
  const ctx = getGitContext();
  const id = shortId();
  const lines = [
    '---',
    `day: ${today()}`,
    `tags: [swr, journal, day/${today()}]`,
    `branch: ${ctx.branch}`,
    `head: ${ctx.head}`,
    `session_id: ${id}`,
    '---',
    '',
    `# SWR — ${today()}`,
    '',
    '> Auto-generated by `tools/swr-journal-log.mjs`. Edit freely; the',
    '> orchestrator only appends, it never rewrites.',
    '',
  ];
  writeFileSync(fp, lines.join('\n'));
}

function appendToDaily(text) {
  ensureDailyHeader();
  appendFileSync(journalFile(), text.trimEnd() + '\n\n');
}

function ensureMoc() {
  const mocPath = join(MOCS, 'SWR.md');
  if (existsSync(mocPath)) return;
  ensureDir(MOCS);
  writeFileSync(mocPath, [
    '---',
    'tags: [map-of-content, swr]',
    '---',
    '# SWR Vault — Map of Contents',
    '',
    '> Index of every Journal entry, audit, design plan, and migration',
    '> recipe. The orchestrator (`tools/swr-journal-log.mjs`) appends to',
    '> `Journal/` and the user updates the MOC by hand or runs the',
    '> script\'s `init` subcommand.',
    '',
    '## Journal (last 30 days)',
    '```dataview',
    'TABLE day AS "Day", file.link AS "Entry", tags',
    'FROM "Journal"',
    'SORT day DESC',
    'LIMIT 30',
    '```',
    '',
    '## Active P0/P1 backlog (from docs/PLANS)',
    '```dataview',
    'LIST',
    'FROM #plan',
    'WHERE contains(tags, "live")',
    '```',
    '',
  ].join('\n'));
}

// ---- Subcommands ----------------------------------------------------

function subcommandInit() {
  ensureDailyHeader();
  ensureMoc();
  console.log('init: vault=' + VAULT + ' journal=' + journalFile());
}

function subcommandCommit(sha, filePath) {
  if (!sha) throw new Error('commit <sha> requires a hash');
  ensureDailyHeader();
  const subject = readShow(sha);
  const files = filePath ? [filePath] : readChangedFiles(sha);
  const ctx = getGitContext();
  const block = [
    '## Commit ' + shortHash(sha) + ' · ' + ctx.branch,
    '',
    '- **Subject:** ' + subject,
    '- **Author:** ' + ctx.author,
    '- **Files:**',
    ...files.map((f) => '  - `' + f + '`'),
    '',
  ].join('\n');
  appendToDaily(block);
  console.log('logged commit ' + shortHash(sha));
}

function subcommandEvent(type, rest) {
  ensureDailyHeader();
  // rest is an array of --key "value" pairs (simple parser)
  const kv = {};
  for (let i = 0; i < rest.length; i += 2) {
    const k = (rest[i] || '').replace(/^--/, '');
    const v = rest[i + 1] || '';
    if (k) kv[k] = v;
  }
  if (!type || !kv.summary) {
    throw new Error('event <type> --summary "..." required');
  }
  const block = [
    '## Event · ' + type + ' · ' + (kv.at || new Date().toISOString()),
    '',
    kv.summary,
    '',
    Object.keys(kv).filter((k) => k !== 'summary' && k !== 'at')
      .map((k) => '- **' + k + ':** ' + kv[k])
      .join('\n'),
    '',
  ].join('\n');
  appendToDaily(block);
  console.log('logged event ' + type);
}

function subcommandSession(summaryPath) {
  ensureDailyHeader();
  const summary = summaryPath
    ? readSafe(summaryPath)
    : process.env.SWR_SESSION_SUMMARY || '';
  const ctx = getGitContext();
  const block = [
    '## Session end · ' + new Date().toISOString(),
    '',
    '- **Branch:** ' + ctx.branch,
    '- **Head at session end:** ' + ctx.head,
    summary ? '' : null,
    summary ? '### Summary' : null,
    summary ? summary : null,
    '',
  ].filter((l) => l !== null).join('\n');
  appendToDaily(block);
  console.log('logged session end at ' + journalFile());
}

function subcommandReadme() {
  ensureMoc();
  console.log('moc: ' + join(MOCS, 'SWR.md'));
}

// ---- Dispatch --------------------------------------------------------

const [, , cmd, ...rest] = process.argv;
try {
  if (cmd === 'init')             subcommandInit();
  else if (cmd === 'commit')      subcommandCommit(rest[0], rest[1]);
  else if (cmd === 'event')       subcommandEvent(rest[0], rest.slice(1));
  else if (cmd === 'session')     subcommandSession(rest[0]);
  else if (cmd === 'readme')      subcommandReadme();
  else {
    process.stdout.write([
      'usage: node tools/swr-journal-log.mjs <subcommand>',
      '',
      'subcommands:',
      '  init                              bootstrap today\'s journal + MOC',
      '  commit <sha> [path]               log one commit (post-commit hook)',
      '  event <type> --key "value" ...    log a structured event',
      '  session [summary file]            log session end (use SWR_SESSION_SUMMARY env var)',
      '  readme                            re-emit the MOC',
      '',
      'vault: ' + VAULT,
    ].join('\n') + '\n');
    process.exit(cmd ? 1 : 0);
  }
} catch (e) {
  console.error('swr-journal-log: ' + e.message);
  process.exit(1);
}
